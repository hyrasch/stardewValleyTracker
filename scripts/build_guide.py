"""Embed guide/Min-Max_Guide.md into js/guide-data.js so the page needs no fetch().

Usage: python -I scripts/build_guide.py
Refresh the guide first with:
  curl -L -o guide/Min-Max_Guide.md https://raw.githubusercontent.com/Zamiell/stardew-valley/main/Min-Max_Guide.md
"""
import json, os, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, 'guide', 'Min-Max_Guide.md')
out = os.path.join(ROOT, 'js', 'guide-data.js')

with open(src, 'r', encoding='utf-8') as f:
    md = f.read()

meta = {
    'title': 'Stardew Valley Min-Max Routing / Strategy',
    'authors': 'BlackSight6 & Zamiel',
    'source': 'https://github.com/Zamiell/stardew-valley/blob/main/Min-Max_Guide.md',
    'license': 'GPL-3.0',
    'licenseUrl': 'https://github.com/Zamiell/stardew-valley/blob/main/LICENSE',
    'snapshot': datetime.date.today().isoformat(),
}
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* Generated by scripts/build_guide.py - do not edit by hand. */\n')
    f.write('const GUIDE_META = ' + json.dumps(meta, ensure_ascii=False) + ';\n')
    f.write('const GUIDE_MD = ' + json.dumps(md, ensure_ascii=False) + ';\n')
print('wrote', out, len(md), 'chars')
